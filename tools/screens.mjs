import { chromium } from 'playwright';
const browser = await chromium.launch();
const page = await browser.newPage({ viewport: { width: 1500, height: 1100 }, deviceScaleFactor: 1 });
await page.goto('http://127.0.0.1:8081/', { waitUntil: 'networkidle' });
await page.click('#btn-solve');
await page.waitForSelector('#metric-cards .metric');
await page.waitForTimeout(500);
await page.screenshot({ path: 'shot-trainer.png', fullPage: true });
await page.click('.tab[data-tab="sandbox"]');
await page.waitForSelector('#sandbox-metrics .metric');
await page.waitForTimeout(400);
await page.screenshot({ path: 'shot-sandbox.png', fullPage: true });
await page.click('.tab[data-tab="experiment"]');
await page.fill('#repeats', '5');
await page.click('#btn-series');
await page.waitForSelector('#series-table tbody tr');
await page.waitForTimeout(400);
await page.screenshot({ path: 'shot-experiment.png', fullPage: true });
await browser.close();
console.log('снимки готовы');
